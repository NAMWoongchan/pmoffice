import test from 'node:test';import assert from 'node:assert/strict';import fs from 'node:fs';import {PGlite} from '@electric-sql/pglite';
test('live PostgreSQL policies: public/member/assigned, suspension, expiry, cross-project, admin, concurrency and direct REST grants',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create schema auth;create schema pmoffice_private;
 create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
 create table auth.identities(user_id uuid,provider text,identity_data jsonb);
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
 create table public.profiles(id uuid primary key,status text,signup_accepted_at timestamptz,signup_version text);
 create table pmoffice_private.service_settings(singleton boolean,signup_version text);
 insert into pmoffice_private.service_settings values(true,'v1');
 create function pmoffice_private.account_ok() returns boolean language sql as $$select exists(select 1 from public.profiles p where p.id=auth.uid() and status='active' and signup_accepted_at is not null and signup_version='v1')$$;
 create function pmoffice_private.is_admin() returns boolean language sql as $$select coalesce(auth.uid()='00000000-0000-0000-0000-000000000001'::uuid and pmoffice_private.account_ok(),false)$$;
 insert into auth.users values ('00000000-0000-0000-0000-000000000001','admin@test',now()),('00000000-0000-0000-0000-000000000002','member@test',now()),('00000000-0000-0000-0000-000000000003','other@test',now());
 insert into auth.identities select id,'google','{"email_verified":true}'::jsonb from auth.users;
 insert into public.profiles select id,'active',now(),'v1' from auth.users;`);
 await db.exec(fs.readFileSync('supabase/migrations/202610200001_pms.sql','utf8'));
 const uid=async n=>db.exec("select set_config('test.uid','"+(n?'00000000-0000-0000-0000-'+String(n).padStart(12,'0'):'')+"',false)");
 const access=async slug=>(await db.query('select public.pms_access($1) as a',[slug])).rows[0].a;
 const save=async(p,v)=>db.query('select public.pms_save_project($1,$2)',[p,v]);
 await uid(null);assert.equal((await access('korail')).allowed,false);
 await uid(1);await save({slug:'korail',title:'Korail',access_mode:'public',status:'published',listed:true},1);
 await uid(null);assert.equal((await access('korail')).allowed,true);
 await assert.rejects(()=>save({slug:'evil',title:'x',access_mode:'public',status:'published'},0));
 await uid(1);await save({slug:'korail',title:'Korail',access_mode:'members',status:'published',listed:true},2);
 await uid(null);assert.equal((await access('korail')).allowed,false);
 await uid(2);assert.equal((await access('korail')).allowed,true);
 await db.exec("update profiles set status='suspended' where id=auth.uid()");assert.equal((await access('korail')).allowed,false);
 await db.exec("update profiles set status='active',signup_version='old' where id=auth.uid()");assert.equal((await access('korail')).allowed,false);
 await db.exec("update profiles set signup_version='v1' where id=auth.uid()");
 await uid(1);await save({slug:'korail',title:'Korail',access_mode:'assigned',status:'published',listed:false},3);
 await db.query('select pms_set_member($1,$2,true,null)',['korail','00000000-0000-0000-0000-000000000002']);
 await save({slug:'another',title:'Another',access_mode:'assigned',status:'published',listed:false},0);
 await uid(2);assert.equal((await access('korail')).allowed,true);assert.equal((await access('another')).allowed,false);
 await uid(3);assert.equal((await access('korail')).allowed,false);
 await uid(1);await db.query('select pms_set_member($1,$2,true,$3)',['korail','00000000-0000-0000-0000-000000000002','2020-01-01']);
 await uid(2);assert.equal((await access('korail')).allowed,false);
 await uid(1);await assert.rejects(()=>save({slug:'korail',title:'stale',access_mode:'public',status:'published'},1));
 await db.exec("set role authenticated");
 await assert.rejects(()=>db.query('select * from public.pms_projects'));
 await assert.rejects(()=>db.exec("update public.pms_projects set access_mode='public'"));
 await db.exec('reset role');await db.close();
});

